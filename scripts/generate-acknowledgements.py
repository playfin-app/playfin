#!/usr/bin/env python3
"""Generates the list of third-party licences: the "Acknowledgements" screen of the app and THIRD_PARTY_LICENSES.md.

Sources: the Rust crates actually linked (`cargo tree -e normal`) and the native libraries shipped by MPVKit.
To be rerun after a change of dependencies: `scripts/generate-acknowledgements.py`.
"""
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Native libraries embedded by MPVKit (LGPL build, without GPL components).
NATIVE = [
    ("mpv", "LGPL-2.1-or-later", "Video player (libmpv)"),
    ("FFmpeg", "LGPL-2.1-or-later", "Audio and video decoding"),
    ("MPVKit", "LGPL-3.0", "libmpv integration on macOS"),
    ("libass", "ISC", "ASS/SSA subtitle rendering"),
    ("libplacebo", "LGPL-2.1-or-later", "Video rendering"),
    ("dav1d", "BSD-2-Clause", "AV1 decoder"),
    ("FreeType", "FTL OR GPL-2.0", "Font rendering"),
    ("HarfBuzz", "MIT", "Text shaping"),
    ("FriBidi", "LGPL-2.1-or-later", "Bidirectional text"),
    ("libbluray", "LGPL-2.1-or-later", "Lecture Blu-ray"),
    ("LuaJIT", "MIT", "Scripts mpv"),
    ("uchardet", "MPL-1.1 OR GPL-2.0 OR LGPL-2.1", "Subtitle encoding detection"),
    ("libunibreak", "Zlib", "Coupures de lignes"),
    ("Little CMS", "MIT", "Colour management"),
    ("shaderc", "Apache-2.0", "Compilation de shaders"),
    ("libdovi", "MIT", "Dolby Vision metadata"),
    ("uavs3d", "BSD-4-Clause", "AVS3 decoder"),
    ("GnuTLS", "LGPL-2.1-or-later", "Encrypted connections (mpv)"),
    ("Nettle", "LGPL-3.0-or-later", "Cryptographie (GnuTLS)"),
    ("GMP", "LGPL-3.0-or-later", "Arithmetic (GnuTLS)"),
    ("OpenSSL", "Apache-2.0", "Cryptographie (FFmpeg)"),
]


def rust_crates():
    out = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--prefix", "none", "--format", "{p}|{l}"],
        cwd=ROOT / "core", capture_output=True, text=True, check=True,
    ).stdout
    crates = {}
    for line in out.splitlines():
        if "|" not in line:
            continue
        package, licence = line.split("|", 1)
        name = package.split(" ")[0]
        version = package.split(" ")[1] if " " in package else ""
        if name == "playfin_core" or "(" in package.split(" v")[-1] and "proc-macro" in package:
            continue
        crates[name] = (version.lstrip("v"), licence.replace(" (*)", "").strip() or "unknown")
    return sorted(crates.items())


def main():
    crates = rust_crates()
    data = {
        "native": [{"name": n, "license": l, "role": r} for n, l, r in NATIVE],
        "rust": [{"name": n, "version": v, "license": l} for n, (v, l) in crates],
    }
    (ROOT / "macos/Playfin/Resources/Acknowledgements.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    lines = [
        "# Licences tierces",
        "",
        "Playfin is distributed under the MPL-2.0 licence (see `LICENSE`). It bundles the following components.",
        "This file is generated by `scripts/generate-acknowledgements.py`.",
        "",
        "## Native libraries (via MPVKit, LGPL build)",
        "",
        "| Component | Licence | Role |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {l} | {r} |" for n, l, r in NATIVE]
    lines += [
        "",
        "mpv and FFmpeg are dynamically linked (separate frameworks in the app), in accordance with the LGPL: "
        "they can be replaced by a modified version.",
        "",
        "## Rust crates (core)",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {l} |" for n, (v, l) in crates]
    (ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(NATIVE)} native libraries, {len(crates)} Rust crates")


if __name__ == "__main__":
    main()
